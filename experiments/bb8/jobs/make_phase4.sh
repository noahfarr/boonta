#!/bin/bash
# Writes jobs/${PHASE4_DIR}_<algorithm>_<game>.txt: every arm × SEEDS for one algorithm and game. Run with bash.
# Calibration (calibration.env, written by calibrate.py from runs finished before Phase 4):
#   STEP                  PPO step option chosen from E1 (lr, lr_sqrt or kl)
#   NOISE_SPACE           noise scale BB-8 uses (fresh, trust_region or gradient), chosen from E1
#   PQN_NOISE_SPACE       same for PQN (fresh or gradient)
#   EARLY_CAP             multiplier cap in the first 10% of training (1, or 2 if E1 supports it)
#   MMAX_<game>, KLMAX_<game>, KLMED_<game>, PQN_MMAX_<game>   see calibrate.py
# Every PPO arm stops (and counts as a stall) when the policy entropy falls below 1% of its first epoch's.
cd "$(dirname "$0")/.." && source budgets.sh && source ${CALIBRATION:-calibration.env}
R=/pfss/mlde/workspaces/mlde_wsp_RAI_WS/ar44ruca; O=$R/bb8_runs/${PHASE4_DIR:-phase4}
SEEDS=${SEEDS:-$(seq 0 15)}
GAMES_PPO=${GAMES_PPO:-"breakout asterix space_invaders"}
GAMES_PQN=${GAMES_PQN:-"breakout asterix"}
STOP="+stop_entropy_fraction=0.01"
CAPS="podracer.config.multiplier_cap=1.0 podracer.config.early_multiplier_cap=$EARLY_CAP podracer.config.early_fraction=0.1"
POOL_PPO="podracer=bb8_pool podracer.config.minibatch_envs=512 podracer.config.running_normalization_below=8192 podracer.config.probe_every=8 podracer.config.noise_source=actor podracer.config.noise_space=$NOISE_SPACE algorithm.bb8.decay=0.7 $CAPS"
POOL_PQN="podracer=bb8_pool environment.num_envs=8192 podracer.config.minibatch_envs=256 podracer.config.probe_every=8 podracer.config.noise_source=td podracer.config.noise_space=$PQN_NOISE_SPACE algorithm.bb8.decay=0.7 $CAPS"

line() { # arm seed overrides...
  local arm=$1 seed=$2; shift 2
  local d=$O/$ALG/$GAME/$arm/$seed
  # Skipped only when it finished before (final time row, or stopped for entropy), so a resubmission reruns crashes.
  echo "mkdir -p $d && { grep -q 'time  ' $d/train.log 2>/dev/null || [ -f $d/stalled.json ] || boonta train algorithm=$ALG environment=gymnax/minatar/$GAME seed=$seed logger=file $* hydra.run.dir=$d > $d/train.log 2>&1; }"
}

for ALG in ppo pqn; do
  if [ $ALG = ppo ]; then GAMES_HERE=$GAMES_PPO; else GAMES_HERE=$GAMES_PQN; fi
  for GAME in $GAMES_HERE; do
    out=jobs/${PHASE4_DIR:-phase4}_${ALG}_${GAME}.txt
    {
      echo "# Phase 4, $ALG $GAME, seeds: $(echo $SEEDS). Generated by make_phase4.sh with ${CALIBRATION:-calibration.env}."
      if [ $ALG = ppo ]; then
        B="$TUNED $TUNED_BUDGET $STOP"
        m=MMAX_$GAME; k=KLMAX_$GAME; km=KLMED_$GAME
        case $STEP in
          kl) ADAPT="podracer.config.step=kl podracer.config.kl_max=${!k}" ;;
          *)  ADAPT="podracer.config.step=$STEP podracer.config.multiplier_max=${!m}" ;;
        esac
        for s in $SEEDS; do
          line tuned_fixed $s $B
          line tuned_anneal $s $B $POOL_PPO podracer.config.schedule=fixed podracer.config.fixed_bucket=8192 podracer.config.step=anneal
          line kl_alone $s $B $POOL_PPO podracer.config.schedule=fixed podracer.config.fixed_bucket=8192 podracer.config.step=kl_constant podracer.config.kl_max=${!km}
          line kl_decay $s $B $POOL_PPO podracer.config.schedule=fixed podracer.config.fixed_bucket=8192 podracer.config.step=kl_decay podracer.config.kl_max=${!km}
          for n in 256 512 1024 2048 4096 8192; do
            line fixed_$n $s $B $POOL_PPO podracer.config.schedule=fixed podracer.config.fixed_bucket=$n $ADAPT
          done
          for n in 256 512; do
            line fixed_${n}_anneal $s $B $POOL_PPO podracer.config.schedule=fixed podracer.config.fixed_bucket=$n podracer.config.step=anneal
          done
          line doubling $s $B $POOL_PPO podracer.config.schedule=doubling $ADAPT
          line naive $s $B $POOL_PPO podracer.config.schedule=noise podracer.config.kappa=1.0 podracer.config.step=none
          line bb8_k0.25 $s $B $POOL_PPO podracer.config.schedule=noise podracer.config.kappa=0.25 $ADAPT
          line bb8_k1 $s $B $POOL_PPO podracer.config.schedule=noise podracer.config.kappa=1.0 $ADAPT
        done
      else
        B="$PQN_BUDGET"
        m=PQN_MMAX_$GAME
        ADAPT="podracer.config.step=lr podracer.config.multiplier_max=${!m}"
        for s in $SEEDS; do
          line default_fixed $s $B
          line default_anneal $s $B podracer=bb8_pool environment.num_envs=4096 "podracer.config.buckets=[256,512,1024,2048,4096]" podracer.config.minibatch_envs=256 podracer.config.schedule=fixed podracer.config.fixed_bucket=4096 podracer.config.step=anneal
          for n in 256 512 1024 2048 4096 8192; do
            line fixed_$n $s $B $POOL_PQN podracer.config.schedule=fixed podracer.config.fixed_bucket=$n $ADAPT
          done
          line naive $s $B $POOL_PQN podracer.config.schedule=noise podracer.config.kappa=1.0 podracer.config.step=none
          line bb8_k0.25 $s $B $POOL_PQN podracer.config.schedule=noise podracer.config.kappa=0.25 $ADAPT
        done
      fi
    } > $out
    echo "$out: $(grep -vc '^#' $out) runs"
  done
done
