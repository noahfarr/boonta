#!/bin/bash
# Writes jobs/e2.txt. Run with bash (zsh does not word-split $GAMES).
cd "$(dirname "$0")/.." && source budgets.sh
O=/pfss/mlde/workspaces/mlde_wsp_RAI_WS/ar44ruca/bb8_runs/e2
{
echo "# E2: noise scale over training, probe on, checkpoints every epoch. Seeds 0-3. Generated by make_e2.sh."
for g in $GAMES; do for s in 0 1 2 3; do d=$O/ppo_$g/$s; echo "mkdir -p $d && boonta train algorithm=ppo environment=gymnax/minatar/$g $PPO_BUDGET seed=$s logger=[file,orbax] algorithm.bb8.noise_scale_probe=true hydra.run.dir=$d > $d/train.log 2>&1"; done; done
for g in breakout asterix; do for s in 0 1 2 3; do d=$O/pqn_$g/$s; echo "mkdir -p $d && boonta train algorithm=pqn environment=gymnax/minatar/$g $PQN_BUDGET seed=$s logger=[file,orbax] algorithm.bb8.noise_scale_probe=true hydra.run.dir=$d > $d/train.log 2>&1"; done; done
D=/pfss/mlde/workspaces/mlde_wsp_RAI_WS/ar44ruca/bb8_runs/phase0/bitwise/autotune0
echo "mkdir -p $D && XLA_FLAGS='--xla_gpu_deterministic_ops=true --xla_gpu_autotune_level=0' bash experiments/bb8/bitwise_check.sh /pfss/mlde/workspaces/mlde_wsp_RAI_WS/ar44ruca/bb8_main $D > $D/bitwise.log 2>&1"
} > jobs/e2.txt
